// Command gen builds internal/apispec/ops_gen.go from the vendored
// Cloudflare OpenAPI spec (internal/apispec/openapi.json.gz).
//
// Usage (from internal/apispec, via `go generate ./...`):
//
//	go run ./gen                      # regenerate ops_gen.go from the vendored spec
//	go run ./gen -import <dir>        # vendor <dir>/openapi.json from a
//	                                  # cloudflare/api-schemas checkout, then regenerate
//
// The import mode minifies and gzips the spec and records the checkout's
// commit and date in spec-source.json. See scripts/update-spec.sh.
package main

import (
	"bytes"
	"compress/gzip"
	"encoding/json"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"os/exec"
	"path/filepath"
	"regexp"
	"sort"
	"strconv"
	"strings"
)

type source struct {
	Repo   string `json:"repo"`
	Commit string `json:"commit"`
	Date   string `json:"date"`
}

func main() {
	importDir := flag.String("import", "", "path to a cloudflare/api-schemas checkout to vendor")
	dir := flag.String("dir", ".", "the internal/apispec directory")
	flag.Parse()
	log.SetFlags(0)
	log.SetPrefix("apispec/gen: ")

	if *importDir != "" {
		if err := vendor(*importDir, *dir); err != nil {
			log.Fatal(err)
		}
	}
	if err := generate(*dir); err != nil {
		log.Fatal(err)
	}
}

func vendor(src, dir string) error {
	raw, err := os.ReadFile(filepath.Join(src, "openapi.json"))
	if err != nil {
		return err
	}
	var buf bytes.Buffer
	if err := json.Compact(&buf, raw); err != nil {
		return fmt.Errorf("openapi.json is not valid JSON: %w", err)
	}
	var gz bytes.Buffer
	zw, _ := gzip.NewWriterLevel(&gz, gzip.BestCompression)
	zw.Write(buf.Bytes())
	zw.Close()
	if err := os.WriteFile(filepath.Join(dir, "openapi.json.gz"), gz.Bytes(), 0o644); err != nil {
		return err
	}
	git := func(args ...string) string {
		out, err := exec.Command("git", append([]string{"-C", src}, args...)...).Output()
		if err != nil {
			return "unknown"
		}
		return strings.TrimSpace(string(out))
	}
	meta := source{Repo: "https://github.com/cloudflare/api-schemas", Commit: git("rev-parse", "HEAD"), Date: git("log", "-1", "--format=%cI")}
	b, _ := json.MarshalIndent(meta, "", "  ")
	log.Printf("vendored spec %s (%s), %d bytes gzipped", meta.Commit, meta.Date, gz.Len())
	return os.WriteFile(filepath.Join(dir, "spec-source.json"), append(b, '\n'), 0o644)
}

// --- spec model (just what we need) ---

type obj = map[string]any

type spec struct {
	root obj
}

func (s *spec) resolve(v any) obj {
	o, _ := v.(obj)
	for i := 0; i < 10 && o != nil; i++ {
		ref, ok := o["$ref"].(string)
		if !ok {
			return o
		}
		o = s.lookup(ref)
	}
	return o
}

func (s *spec) lookup(ref string) obj {
	if !strings.HasPrefix(ref, "#/") {
		return nil
	}
	var cur any = s.root
	for _, p := range strings.Split(ref[2:], "/") {
		p = strings.ReplaceAll(strings.ReplaceAll(p, "~1", "/"), "~0", "~")
		m, ok := cur.(obj)
		if !ok {
			return nil
		}
		cur = m[p]
	}
	o, _ := cur.(obj)
	return o
}

// --- generated table types (must match apispec.Op / apispec.Param) ---

type param struct {
	Name, In, Type, Default, Desc string
	Required                      bool
	Enum                          []string
}

type op struct {
	ID, Method, Path, Tag, TagSlug, Slug, Summary, Desc string
	Deprecated, Confirm                                 bool
	Params                                              []param
	BodyTypes                                           []string
	BodyRequired                                        bool
}

var methods = []string{"get", "post", "put", "patch", "delete", "head", "options"}

var pathParamRE = regexp.MustCompile(`\{([^}]+)\}`)

func generate(dir string) error {
	f, err := os.Open(filepath.Join(dir, "openapi.json.gz"))
	if err != nil {
		return err
	}
	defer f.Close()
	zr, err := gzip.NewReader(f)
	if err != nil {
		return err
	}
	var root obj
	dec := json.NewDecoder(zr)
	dec.UseNumber()
	if err := dec.Decode(&root); err != nil {
		return err
	}
	var meta source
	if b, err := os.ReadFile(filepath.Join(dir, "spec-source.json")); err == nil {
		json.Unmarshal(b, &meta)
	}
	s := &spec{root: root}

	paths, _ := root["paths"].(obj)
	pathKeys := make([]string, 0, len(paths))
	for p := range paths {
		pathKeys = append(pathKeys, p)
	}
	sort.Strings(pathKeys)

	var ops []*op
	for _, p := range pathKeys {
		item, _ := paths[p].(obj)
		for _, m := range methods {
			raw, ok := item[m].(obj)
			if !ok {
				continue
			}
			ops = append(ops, buildOp(s, p, m, item, raw))
		}
	}
	assignSlugs(ops)

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/apispec/gen; DO NOT EDIT.\n")
	fmt.Fprintf(&b, "//\n// Source: %s @ %s (%s)\n// Operations: %d\n\n", meta.Repo, meta.Commit, meta.Date, len(ops))
	fmt.Fprintf(&b, "package apispec\n\n")
	fmt.Fprintf(&b, "// Spec source, recorded by `go run ./gen -import`.\nconst (\n\tSpecRepo = %q\n\tSpecCommit = %q\n\tSpecDate = %q\n\tSpecOpenAPI = %q\n\tSpecVersion = %q\n)\n\n",
		meta.Repo, meta.Commit, meta.Date, str(root["openapi"]), str(s.resolve(root["info"])["version"]))
	fmt.Fprintf(&b, "var ops = []Op{\n")
	for _, o := range ops {
		fmt.Fprintf(&b, "{ID: %q, Method: %q, Path: %q, Tag: %q, TagSlug: %q, Slug: %q, Summary: %q, Desc: %q",
			o.ID, o.Method, o.Path, o.Tag, o.TagSlug, o.Slug, o.Summary, o.Desc)
		if o.Deprecated {
			b.WriteString(", Deprecated: true")
		}
		if o.Confirm {
			b.WriteString(", Confirm: true")
		}
		if len(o.Params) > 0 {
			b.WriteString(", Params: []Param{")
			for _, pr := range o.Params {
				fmt.Fprintf(&b, "{Name: %q, In: %q, Type: %q", pr.Name, pr.In, pr.Type)
				if pr.Required {
					b.WriteString(", Required: true")
				}
				if pr.Default != "" {
					fmt.Fprintf(&b, ", Default: %q", pr.Default)
				}
				if len(pr.Enum) > 0 {
					fmt.Fprintf(&b, ", Enum: %#v", pr.Enum)
				}
				if pr.Desc != "" {
					fmt.Fprintf(&b, ", Desc: %q", pr.Desc)
				}
				b.WriteString("},")
			}
			b.WriteString("}")
		}
		if len(o.BodyTypes) > 0 {
			fmt.Fprintf(&b, ", BodyTypes: %#v", o.BodyTypes)
		}
		if o.BodyRequired {
			b.WriteString(", BodyRequired: true")
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return fmt.Errorf("gofmt generated code: %w", err)
	}
	log.Printf("wrote ops_gen.go: %d operations, %d tags", len(ops), countTags(ops))
	return os.WriteFile(filepath.Join(dir, "ops_gen.go"), src, 0o644)
}

func countTags(ops []*op) int {
	m := map[string]bool{}
	for _, o := range ops {
		m[o.TagSlug] = true
	}
	return len(m)
}

func str(v any) string {
	switch x := v.(type) {
	case string:
		return x
	case json.Number:
		return x.String()
	case bool:
		return strconv.FormatBool(x)
	case nil:
		return ""
	}
	b, _ := json.Marshal(v)
	return string(b)
}

func firstLine(s string, max int) string {
	for _, line := range strings.Split(s, "\n") {
		line = strings.TrimSpace(line)
		if line == "" {
			continue
		}
		line = strings.Join(strings.Fields(line), " ")
		if len(line) > max {
			cut := strings.LastIndex(line[:max], " ")
			if cut < max/2 {
				cut = max
			}
			line = line[:cut] + "…"
		}
		return line
	}
	return ""
}

func buildOp(s *spec, path, method string, item, raw obj) *op {
	o := &op{
		ID:      str(raw["operationId"]),
		Method:  strings.ToUpper(method),
		Path:    path,
		Summary: strings.TrimSpace(str(raw["summary"])),
		Desc:    firstLine(str(raw["description"]), 200),
	}
	if o.ID == "" {
		o.ID = method + strings.ReplaceAll(path, "/", "_")
	}
	if tags, ok := raw["tags"].([]any); ok && len(tags) > 0 {
		o.Tag = str(tags[0])
	}
	if o.Tag == "" {
		o.Tag = "Other"
	}
	if o.Summary == "" {
		o.Summary = o.ID
	}
	o.Deprecated, _ = raw["deprecated"].(bool)
	if _, ok := raw["x-stainless-deprecation-message"]; ok {
		o.Deprecated = true
	}
	o.Confirm, _ = raw["x-forge-require-confirmation"].(bool)

	// Path-level params first; operation-level ones override by (in, name).
	declared := map[string]param{}
	var order []string
	add := func(list any) {
		arr, _ := list.([]any)
		for _, pv := range arr {
			p := s.resolve(pv)
			if p == nil {
				continue
			}
			pr := toParam(s, p)
			key := pr.In + ":" + pr.Name
			if _, seen := declared[key]; !seen {
				order = append(order, key)
			}
			declared[key] = pr
		}
	}
	add(item["parameters"])
	add(raw["parameters"])

	// Path params in template order (whether declared or not).
	for _, m := range pathParamRE.FindAllStringSubmatch(path, -1) {
		name := m[1]
		pr, ok := declared["path:"+name]
		if !ok {
			pr = param{Name: name, In: "path", Type: "string"}
		}
		pr.Required = true
		o.Params = append(o.Params, pr)
	}
	for _, in := range []string{"query", "header", "cookie"} {
		for _, key := range order {
			if pr := declared[key]; pr.In == in {
				o.Params = append(o.Params, pr)
			}
		}
	}

	if rb := s.resolve(raw["requestBody"]); rb != nil {
		o.BodyRequired, _ = rb["required"].(bool)
		content, _ := rb["content"].(obj)
		for ct := range content {
			o.BodyTypes = append(o.BodyTypes, ct)
		}
		sort.Slice(o.BodyTypes, func(i, j int) bool {
			return bodyRank(o.BodyTypes[i]) < bodyRank(o.BodyTypes[j]) ||
				(bodyRank(o.BodyTypes[i]) == bodyRank(o.BodyTypes[j]) && o.BodyTypes[i] < o.BodyTypes[j])
		})
		if len(o.BodyTypes) == 0 {
			o.BodyTypes = []string{"application/json"}
		}
	}
	return o
}

// bodyRank orders content types so the most CLI-friendly comes first.
func bodyRank(ct string) int {
	switch {
	case ct == "application/json":
		return 0
	case strings.Contains(ct, "json"):
		return 1
	case ct == "multipart/form-data":
		return 2
	}
	return 3
}

func toParam(s *spec, p obj) param {
	pr := param{Name: str(p["name"]), In: str(p["in"]), Desc: firstLine(str(p["description"]), 140)}
	pr.Required, _ = p["required"].(bool)
	sch := s.resolve(p["schema"])
	pr.Type = schemaType(s, sch)
	if sch != nil {
		if d, ok := sch["default"]; ok {
			pr.Default = str(d)
		}
		enum := sch["enum"]
		if pr.Type == "array" || strings.HasPrefix(pr.Type, "array<") {
			if items := s.resolve(sch["items"]); items != nil {
				enum = items["enum"]
			}
		}
		if arr, ok := enum.([]any); ok {
			for _, e := range arr {
				if e != nil {
					pr.Enum = append(pr.Enum, str(e))
				}
			}
		}
		if pr.Desc == "" {
			pr.Desc = firstLine(str(sch["description"]), 140)
		}
	}
	return pr
}

func schemaType(s *spec, sch obj) string {
	if sch == nil {
		return "string"
	}
	t := str(sch["type"])
	if t == "" {
		for _, k := range []string{"allOf", "anyOf", "oneOf"} {
			if arr, ok := sch[k].([]any); ok && len(arr) > 0 {
				return schemaType(s, s.resolve(arr[0]))
			}
		}
		if _, ok := sch["enum"]; ok {
			return "string"
		}
		return "string"
	}
	if strings.HasPrefix(t, "[") { // OpenAPI 3.1 type arrays
		var ts []string
		json.Unmarshal([]byte(t), &ts)
		for _, x := range ts {
			if x != "null" {
				t = x
				break
			}
		}
	}
	if t == "array" {
		return "array<" + schemaType(s, s.resolve(sch["items"])) + ">"
	}
	return t
}

// --- slugs ---

var (
	parenRE   = regexp.MustCompile(`\([^)]*\)`)
	camel1    = regexp.MustCompile(`([a-z0-9])([A-Z])`)
	camel2    = regexp.MustCompile(`([A-Z]+)([A-Z][a-z])`)
	nonAlnum  = regexp.MustCompile(`[^a-z0-9]+`)
	apostroph = regexp.MustCompile(`['’]`)
)

// kebab turns any text into lowercase-kebab-case.
func kebab(s string, splitCamel bool) string {
	s = apostroph.ReplaceAllString(s, "")
	if splitCamel {
		s = camel2.ReplaceAllString(s, "$1-$2")
		s = camel1.ReplaceAllString(s, "$1-$2")
	}
	s = nonAlnum.ReplaceAllString(strings.ToLower(s), "-")
	return strings.Trim(s, "-")
}

// tagSlug: "Secondary DNS (Primary Zone)" → "secondary-dns-primary-zone".
func tagSlug(tag string) string {
	if s := kebab(tag, false); s != "" {
		return s
	}
	return "other"
}

// summarySlug: "Create an AI Search instance (Search for ...)." → "create-an-ai-search-instance".
func summarySlug(summary string) string {
	s := kebab(parenRE.ReplaceAllString(summary, " "), false)
	if s == "" {
		s = kebab(summary, false)
	}
	return s
}

// idSlug: operationId in kebab-case, minus a redundant tag prefix.
func idSlug(id, tagSlug string) string {
	s := kebab(id, true)
	if t := tagSlug + "-"; strings.HasPrefix(s, t) && len(s) > len(t) {
		s = s[len(t):]
	}
	return s
}

// assignSlugs gives every op a tag slug and an op slug unique within it.
//
//  1. tag slug = kebab(tag). Tags that differ only in case/punctuation
//     ("Webhooks", "webhooks") share one group.
//  2. op slug = kebab(summary without parentheticals).
//  3. ops whose slugs collide within a tag ALL switch to kebab(full summary)
//     (keeping parentheticals: "create-bucket-by-name"), then, if they still
//     collide, to their operationId slug. Unrelated ops never affect each
//     other, so slugs are stable across spec updates.
//  4. remaining collisions get -2, -3, … in operationId order.
func assignSlugs(ops []*op) {
	reserved := map[string]bool{"request": true, "list": true, "tags": true, "search": true, "describe": true, "spec-info": true, "help": true}
	tagSlugs := map[string]string{}
	for _, o := range ops {
		if _, ok := tagSlugs[o.Tag]; ok {
			continue
		}
		s := tagSlug(o.Tag)
		if reserved[s] {
			s += "-api"
		}
		tagSlugs[o.Tag] = s
	}

	byTag := map[string][]*op{}
	for _, o := range ops {
		o.TagSlug = tagSlugs[o.Tag]
		byTag[o.TagSlug] = append(byTag[o.TagSlug], o)
	}
	for _, group := range byTag {
		// Each pass re-slugs only the ops that still collide.
		passes := []func(o *op) string{
			func(o *op) string { return summarySlug(o.Summary) },
			func(o *op) string { return kebab(o.Summary, false) },
			func(o *op) string { return idSlug(o.ID, o.TagSlug) },
		}
		for _, o := range group {
			o.Slug = passes[0](o)
		}
		for _, next := range passes[1:] {
			count := map[string]int{}
			for _, o := range group {
				count[o.Slug]++
			}
			for _, o := range group {
				if count[o.Slug] > 1 || o.Slug == "" || o.Slug == "help" {
					if s := next(o); s != "" {
						o.Slug = s
					}
				}
			}
		}
		sort.Slice(group, func(i, j int) bool { return group[i].ID < group[j].ID })
		used := map[string]bool{}
		for _, o := range group {
			base := o.Slug
			for i := 2; used[o.Slug]; i++ {
				o.Slug = fmt.Sprintf("%s-%d", base, i)
			}
			used[o.Slug] = true
		}
	}
}
